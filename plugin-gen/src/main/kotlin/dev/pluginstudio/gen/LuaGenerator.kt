package dev.pluginstudio.gen

/**
 * Emits a complete NoveLA-compatible Lua plugin from a [PluginBlueprint],
 * following the same conventions as the existing production sources
 * (element .html/.text/.href API, {items,hasNext} catalogs, helpers, cleanup).
 * Selectors are emitted as literals inside their functions so Studio's
 * SelectorExtractor can display them as hints.
 */
object LuaGenerator {

    fun luaEscape(s: String): String =
        s.replace("\\", "\\\\").replace("\"", "\\\"")

    fun generate(bp: PluginBlueprint): String {
        val sb = StringBuilder()
        val b = { s: String -> luaEscape(s) }

        // ── metadata ──
        sb.appendLine("id       = \"${b(bp.id)}\"")
        sb.appendLine("name     = \"${b(bp.name)}\"")
        sb.appendLine("version  = \"1.0.0\"")
        sb.appendLine("baseUrl  = \"${b(bp.baseUrl)}\"")
        sb.appendLine("language = \"${b(bp.language)}\"")
        if (bp.icon.isNotBlank()) sb.appendLine("icon     = \"${b(bp.icon)}\"")
        sb.appendLine()
        sb.appendLine("-- Generated by Plugin Dev Studio (Analyze & Generate).")
        sb.appendLine("-- Strategy variant: ${bp.variantName}. Review selectors and test before publishing.")
        bp.notes.forEach { sb.appendLine("-- $it") }
        sb.appendLine()

        // ── helpers ──
        sb.appendLine("-- ── Helpers ─────────────────────────────────────────────────────────────")
        sb.appendLine("""
local _cache = {}

local function fetchPage(url)
    if _cache[url] then return _cache[url] end
    local r = http_get(url)
    if r.success then
        _cache[url] = r.body
        return r.body
    end
    return nil
end

local function absUrl(href)
    if not href or href == "" then return "" end
    if string_starts_with(href, "http") then return href end
    if string_starts_with(href, "//") then return "https:" .. href end
    return url_resolve(baseUrl, href)
end

local function cleanText(t)
    return string_trim(string_clean(t or ""))
end

local function transformContent(text)
    if not text or text == "" then return "" end
    text = string_normalize(text)
    text = regex_replace(text, "(?im)^\\s*(Translator|Editor|Proofreader|Read\\s+(at|on|latest)|Please\\s+rate)[^\\n\\r]{0,80}(\\r?\\n|$)", "")
    text = regex_replace(text, "(?i)\\A[\\s\\p{Z}\\uFEFF]*((Chapter\\s+\\d+)[^\\n\\r]*[\\n\\r\\s]*){0,3}", "")
    return string_trim(text)
end
""")
        sb.appendLine()

        // ── catalog ──
        bp.catalog?.let { cat ->
            val pageExpr = when (cat.pageParamStyle) {
                "path_page_1" -> "baseUrl .. \"${b(cat.basePath)}/page/\" .. page"
                else -> {
                    val sep = if (cat.basePath.contains("?")) "\"&page=\" .. page" else "\"?page=\" .. page"
                    "baseUrl .. \"${b(cat.basePath)}\" .. $sep"
                }
            }
            sb.appendLine("-- ── Catalog ──")
            sb.appendLine("""
function getCatalogList(index)
    local page = index + 1
    local url = ${pageExpr}
    local body = fetchPage(url)
    if not body then return { items = {}, hasNext = false } end

    local items = {}
${if (cat.anchorOnly) """
    for _, card in ipairs(html_select(body, "${b(cat.containerSel)}")) do
        local linkEl = html_select_first(card.html, "${b(cat.linkSel)}")
        if linkEl and linkEl.href and linkEl.href ~= "" then
            local cover = ""
            local covEl = html_attr(card.html, "${b(cat.coverSel)}", "src")
            if covEl == "" then covEl = html_attr(card.html, "${b(cat.coverSel)}", "data-src") end
            cover = absUrl(covEl)
            table.insert(items, {
                title = cleanText(linkEl.text),
                url   = absUrl(linkEl.href),
                cover = cover
            })
        end
    end""" else """
    for _, card in ipairs(html_select(body, "${b(cat.containerSel)}")) do
        local titleEl = html_select_first(card.html, "${b(cat.titleSel)}")
        local linkEl  = html_select_first(card.html, "${b(cat.linkSel)}")
        if not (titleEl or linkEl) then goto continue end
        local href = (linkEl and linkEl.href) or (titleEl and titleEl.href) or ""
        local titleText = (titleEl and titleEl.text) or (linkEl and linkEl.text) or ""
        if href == "" or titleText == "" then goto continue end
        local covSrc = html_attr(card.html, "${b(cat.coverSel)}", "src")
        if covSrc == "" then covSrc = html_attr(card.html, "${b(cat.coverSel)}", "data-src") end
        table.insert(items, {
            title = cleanText(titleText),
            url   = absUrl(href),
            cover = absUrl(covSrc)
        })
        ::continue::
    end"""}
    return { items = items, hasNext = #items > 0 }
end""")
            sb.appendLine()
        }

        // ── search ──
        bp.searchApi?.let { api ->
            val urlBuild = when {
                api.urlField != null -> "item[\"${b(api.urlField)}\"]"
                api.slugField != null && api.bookUrlPrefix != null ->
                    "\"${b(api.bookUrlPrefix)}\" .. tostring(item[\"${b(api.slugField)}\"])"
                else -> "absUrl(tostring(item[\"url\"] or item[\"link\"] or \"\"))"
            }
            val coverBuild = if (api.coverField != null) "absUrl(tostring(item[\"${b(api.coverField)}\"] or \"\"))" else "\"\""

            sb.appendLine("-- ── Search (JSON API validated during analysis) ──")
            sb.appendLine("""
function getCatalogSearch(index, query)
    if index > 0 then return { items = {}, hasNext = false } end
    local url = string.gsub("${b(api.urlTemplate)}", "{query}", url_encode(query))
    local r = ${if (api.method == "POST") "http_post(url, \"query=\" .. url_encode(query))" else "http_get(url)"}
    if not r.success then return { items = {}, hasNext = false } end
    local data = json_parse(r.body)
    if not data then return { items = {}, hasNext = false } end
    local arr = data
    if type(arr) ~= "table" or #arr == 0 then
        for k, v in pairs(data) do
            if type(v) == "table" and #v > 0 then arr = v break end
        end
    end
    if type(arr) ~= "table" then return { items = {}, hasNext = false } end

    local items = {}
    for _, item in ipairs(arr) do
        if type(item) == "table" then
            local t = tostring(item["${b(api.titleField)}"] or "")
            local u = ${urlBuild}
            if t ~= "" and u ~= "" then
                table.insert(items, { title = cleanText(t), url = u, cover = ${coverBuild} })
            end
        end
    end
    return { items = items, hasNext = false }
end""")
            sb.appendLine()
        } ?: bp.searchDom?.let { form ->
            if (form.containerSel != null) {
                val tSel = form.titleSel ?: "a"
                val linkSelForCard = if (form.linkOnly) tSel else "a"
                val covExpr = form.coverSel?.let { "\"${b(it)}\"" } ?: "\"img\""
                sb.appendLine("-- ── Search (site search results page) ──")
                sb.appendLine("function getCatalogSearch(index, query)")
                sb.appendLine("    if index > 0 then return { items = {}, hasNext = false } end")
                sb.appendLine("    local url = \"${b(form.formAction)}\" ..")
                sb.appendLine("        (string.find(\"${b(form.formAction)}\", \"%?\", 1, true) and \"&\" or \"?\") ..")
                sb.appendLine("        \"${b(form.inputName)}=\" .. url_encode(query)")
                sb.appendLine("    local body = fetchPage(url)")
                sb.appendLine("    if not body then return { items = {}, hasNext = false } end")
                sb.appendLine("    local items = {}")
                sb.appendLine("    for _, card in ipairs(html_select(body, \"${b(form.containerSel)}\")) do")
                sb.appendLine("        local linkEl = html_select_first(card.html, \"${b(linkSelForCard)}\")")
                if (!form.linkOnly && tSel != "a") {
                    sb.appendLine("        local titleEl = html_select_first(card.html, \"${b(tSel)}\")")
                    sb.appendLine("        if not (linkEl or titleEl) then goto continue end")
                    sb.appendLine("        local href = (linkEl and linkEl.href) or (titleEl and titleEl.href) or \"\"")
                    sb.appendLine("        local titleText = (titleEl and titleEl.text) or \"\"")
                } else {
                    sb.appendLine("        if not linkEl then goto continue end")
                    sb.appendLine("        local href = linkEl.href or \"\"")
                    sb.appendLine("        local titleText = linkEl.text or \"\"")
                }
                sb.appendLine("        if href == \"\" or titleText == \"\" then goto continue end")
                sb.appendLine("        table.insert(items, {")
                sb.appendLine("            title = cleanText(titleText),")
                sb.appendLine("            url   = absUrl(href),")
                sb.appendLine("            cover = absUrl(html_attr(card.html, $covExpr, \"src\"))")
                sb.appendLine("        })")
                sb.appendLine("        ::continue::")
                sb.appendLine("    end")
                sb.appendLine("    return { items = items, hasNext = #items > 0 }")
                sb.appendLine("end")
                sb.appendLine()
            }
        }

        // ── book metadata ──
        val bk = bp.book
        if (bk != null && (bk.titleSel != null || bk.coverSel != null || bk.descSel != null || bk.genresSel != null)) {
            sb.appendLine("-- ── Book details ──")
            bk.titleSel?.let { sel ->
                sb.appendLine("""
function getBookTitle(bookUrl)
    local body = fetchPage(bookUrl)
    if not body then return nil end
    local el = html_select_first(body, "${b(sel)}")
    return el and cleanText(el.text) or nil
end""")
            }
            bk.coverSel?.let { sel ->
                sb.appendLine("""

function getBookCoverImageUrl(bookUrl)
    local body = fetchPage(bookUrl)
    if not body then return nil end
    local src = html_attr(body, "${b(sel)}", "src")
    if src == "" then src = html_attr(body, "${b(sel)}", "data-src") end
    if src == "" then src = html_attr(body, "meta[property='og:image']", "content") end
    return src ~= "" and absUrl(src) or nil
end""")
            } ?: sb.appendLine("""

function getBookCoverImageUrl(bookUrl)
    local body = fetchPage(bookUrl)
    if not body then return nil end
    local src = html_attr(body, "meta[property='og:image']", "content")
    return src ~= "" and absUrl(src) or nil
end""")
            bk.descSel?.let { sel ->
                sb.appendLine("""

function getBookDescription(bookUrl)
    local body = fetchPage(bookUrl)
    if not body then return nil end
    local el = html_select_first(body, "${b(sel)}")
    local t = ""
    if el then t = string_trim(el.text) end
    if t == "" then t = html_attr(body, "meta[property='og:description']", "content") end
    return t ~= "" and t or nil
end""")
            }
            bk.genresSel?.let { sel ->
                sb.appendLine("""

function getBookGenres(bookUrl)
    local body = fetchPage(bookUrl)
    if not body then return {} end
    local genres = {}
    for _, el in ipairs(html_select(body, "${b(sel)}")) do
        local label = string_trim(el.text)
        if label ~= "" then table.insert(genres, label) end
    end
    return genres
end""")
            }
            sb.appendLine()
        }

        // ── chapter list ──
        bp.chapters?.let { ch ->
            sb.appendLine("-- ── Chapter list ──")
            sb.appendLine("""
function getChapterList(bookUrl)
    local body = fetchPage(bookUrl)
    if not body then return {} end
    local chapters = {}
    for _, a in ipairs(html_select(body, "${b(ch.anchorsSel)}")) do
        local h = a.href or ""
        if h ~= "" and string_starts_with(h, "/") or string_starts_with(h, "http") then
            table.insert(chapters, {
                title = cleanText(a.text),
                url   = absUrl(h)
            })
        end
    end
    return chapters
end""")
            sb.appendLine()
        }

        // ── chapter text ──
        bp.chapterText?.let { ct ->
            val removes = ct.removeSels.joinToString(", ") { "\"${b(it)}\"" }
            sb.appendLine("-- ── Chapter content ──")
            sb.appendLine("""
function getChapterText(html, url)
    local cleaned = html_remove(html${if (ct.removeSels.isEmpty()) "" else ", $removes"})
${if (ct.contentSel != null) """
    local el = html_select_first(cleaned, "${b(ct.contentSel)}")
    if not el then return "" end
    return transformContent(html_text(el.html))""" else """
    local parts = {}
    for _, p in ipairs(html_select(cleaned, "p")) do
        if #p.text > 0 then parts[#parts + 1] = p.text end
    end
    if #parts == 0 then return "" end
    return transformContent(table.concat(parts, "\\n\\n"))"""}
end""")
            sb.appendLine()
        }

        return sb.toString().replace(Regex("\n{4,}"), "\n\n\n").trimEnd() + "\n"
    }
}
